// Generates supabase/seed.sql from the shared fictional dataset in src/data/catalog.json,
// so the demo backend and the local database always use identical menu data.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const catalog = JSON.parse(readFileSync(resolve(root, 'src/data/catalog.json'), 'utf8'))
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'string' ? `'${v.replaceAll("'", "''")}'` : String(v))

const lines = [
  '-- GENERATED by scripts/generate-seed.mjs from src/data/catalog.json. Do not edit by hand.',
  '-- Local development / demo data only. Do not run against production.',
  '',
  `update public.cafe_settings set cafe_name = ${q(catalog.settings.cafe_name)}, is_open = ${catalog.settings.is_open}, closed_message = ${q(catalog.settings.closed_message)}, upi_id = ${q(catalog.settings.upi_id)}, upi_payee_name = ${q(catalog.settings.upi_payee_name)} where id;`,
  '',
  'insert into public.cafe_tables (label) values',
  catalog.tables.map((t) => `  (${q(t)})`).join(',\n') + ';',
  '',
  'insert into public.categories (id, name, sort_order) values',
  catalog.categories.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${c.sort_order})`).join(',\n') + ';',
  '',
  'insert into public.menu_items (id, category_id, name, description, price, is_veg, is_available, is_popular, sort_order) values',
  catalog.items
    .map((i) => `  (${q(i.id)}, ${q(i.category_id)}, ${q(i.name)}, ${q(i.description)}, ${i.price}, ${i.is_veg}, ${i.is_available}, ${i.is_popular}, ${i.sort_order})`)
    .join(',\n') + ';',
  '',
  'insert into public.addons (id, menu_item_id, name, price, sort_order) values',
  catalog.items
    .flatMap((i) => i.addons.map((a) => `  (${q(a.id)}, ${q(i.id)}, ${q(a.name)}, ${a.price}, ${a.sort_order})`))
    .join(',\n') + ';',
  '',
]
writeFileSync(resolve(root, 'supabase/seed.sql'), lines.join('\n'))
console.log('Wrote supabase/seed.sql')
